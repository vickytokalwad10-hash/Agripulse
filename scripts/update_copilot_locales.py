for lang in LANGUAGES:
    file_path = os.path.join(LOCALES_DIR, lang, "translation.json")
    if os.path.exists(file_path):
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        
        if "copilot" not in data:
            data["copilot"] = {}
        
        for k, lang_map in COPILOT_KEYS.items():
            data["copilot"][k] = lang_map.get(lang, lang_map.get("en", ""))
        
        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"✅ Updated Copilot keys in {lang}/translation.json")

